function icon(key){
 const boss=Object.hasOwn(bosses,key)?bosses[key]:null;
 if(!boss)return null;
 const frame=document.createElement('span');
 frame.className='chronicle-boss-icon'+(boss.files.length>1?' chronicle-boss-group':'');
 frame.dataset.bossKey=key;
 boss.files.forEach((file,index)=>{
  const image=document.createElement('img');
  image.src='img/bosses/'+file;
  image.alt=boss.names[index]||boss.names.join(' & ');
  image.loading='lazy';image.decoding='async';
  image.onerror=()=>{image.hidden=true;if([...frame.children].every(child=>child.hidden))frame.hidden=true};
  frame.append(image);
 });
 return frame;
}
